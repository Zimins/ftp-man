export const DICTS: Record<Lang, Dict> = { ko, en }

export function resolveLang(pref: LangPref): Lang {
  if (pref === 'ko' || pref === 'en') return pref
  const nav = (navigator.language || 'en').toLowerCase()
  return nav.startsWith('ko') ? 'ko' : 'en'
}

export const LangContext = createContext<{ lang: Lang; t: Dict }>({ lang: 'ko', t: ko })

export function useT(): { lang: Lang; t: Dict; locale: string } {
  const { lang, t } = useContext(LangContext)
  return { lang, t, locale: lang === 'ko' ? 'ko-KR' : 'en-US' }
}
